import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = path.join(root, 'contracts', 'agent-sources.json');
const contract = JSON.parse(await readFile(contractPath, 'utf8'));

if (!Array.isArray(contract.sources) || !Array.isArray(contract.comingSoon)) {
  throw new Error('contracts/agent-sources.json has an invalid shape');
}

const rawModuleSource = `// SPDX-License-Identifier: AGPL-3.0-or-later
/* AUTO-GENERATED by scripts/generate-agent-source-declarations.mjs.
 * Edit contracts/agent-sources.json, then run pnpm agent-sources:generate. */
import type {
  AgentSourceAdapterId,
  AgentSourceCatalogEntry,
  AgentSourceDeclaration,
} from '@exawatt/core';

export const AGENT_SOURCE_DECLARATIONS = ${JSON.stringify(contract.sources, null, 2)} as const satisfies readonly AgentSourceDeclaration[];

export const FUTURE_AGENT_SOURCE_CATALOG = ${JSON.stringify(contract.comingSoon, null, 2)} as const satisfies readonly AgentSourceCatalogEntry[];

export function agentSourceDeclaration(
  adapterId: AgentSourceAdapterId
): AgentSourceDeclaration {
  const declaration = AGENT_SOURCE_DECLARATIONS.find(
    candidate => candidate.adapterId === adapterId
  );
  if (!declaration) throw new Error(\`Unknown Agent Source: \${adapterId}\`);
  return declaration;
}
`;

const targets = [
  path.join(root, 'src', 'generated', 'agent-source-declarations.ts'),
  path.join(
    root,
    'electron',
    'main',
    'pty',
    'generated-agent-source-declarations.ts'
  ),
];

const prettierConfig =
  (await resolveConfig(path.join(root, 'src', 'generated'))) ?? {};
const moduleSource = await format(rawModuleSource, {
  ...prettierConfig,
  parser: 'typescript',
});

await Promise.all(targets.map(target => writeFile(target, moduleSource)));
