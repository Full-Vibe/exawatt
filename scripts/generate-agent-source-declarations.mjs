/**
 * Agent Source declarations: one contract, every generated view of it.
 *
 * `contracts/agent-sources.json` is the only place a source is declared. This
 * script derives from it:
 *
 * - the source id lists `@exawatt/core` exports (`AGENT_HARNESSES`,
 *   `AGENT_SOURCE_ADAPTER_IDS`, `AGENT_SOURCE_CATALOG_IDS`), which every
 *   literal id type and runtime guard is built from;
 * - the full declarations, once for the renderer and once for Electron main,
 *   whose build cannot import from `src/`.
 *
 *   node scripts/generate-agent-source-declarations.mjs           write them
 *   node scripts/generate-agent-source-declarations.mjs --check   verify them
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const CHECK = process.argv.includes('--check');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = path.join(root, 'contracts', 'agent-sources.json');
const contract = JSON.parse(await readFile(contractPath, 'utf8'));

if (!Array.isArray(contract.sources) || !Array.isArray(contract.comingSoon)) {
  throw new Error('contracts/agent-sources.json has an invalid shape');
}

/*
 * The id lists below are built from these fields, so a duplicate or a
 * mistyped id would become a duplicate tuple member or a wrong literal type
 * rather than an error. Refuse it here instead.
 */
const seenIds = new Set();
const seenHarnesses = new Set();
for (const entry of [...contract.sources, ...contract.comingSoon]) {
  if (typeof entry.adapterId !== 'string' || !entry.adapterId) {
    throw new Error('Every Agent Source needs a non-empty adapterId');
  }
  if (seenIds.has(entry.adapterId)) {
    throw new Error(`Agent Source ${entry.adapterId} is declared twice`);
  }
  seenIds.add(entry.adapterId);
}
for (const source of contract.sources) {
  if (source.harness === null) continue;
  if (typeof source.harness !== 'string' || !source.harness) {
    throw new Error(
      `Agent Source ${source.adapterId} needs a harness id or null`
    );
  }
  // Main finds a harness's source by this field, so it names one source.
  if (seenHarnesses.has(source.harness)) {
    throw new Error(`Harness ${source.harness} belongs to two Agent Sources`);
  }
  seenHarnesses.add(source.harness);
}

const header = `// SPDX-License-Identifier: AGPL-3.0-or-later
/* AUTO-GENERATED by scripts/generate-agent-source-declarations.mjs.
 * Edit contracts/agent-sources.json, then run pnpm agent-sources:generate. */`;

const tuple = ids => `${JSON.stringify(ids)} as const`;

const harnesses = contract.sources
  .filter(source => source.harness !== null)
  .map(source => source.harness);
const adapterIds = contract.sources.map(source => source.adapterId);
const catalogIds = [
  ...adapterIds,
  ...contract.comingSoon.map(entry => entry.adapterId),
];

const idsModule = `${header}

/** Sources Exawatt runs as a local CLI in a terminal, in contract order. */
export const AGENT_HARNESSES = ${tuple(harnesses)};

/** Every declared Agent Source, in contract order. */
export const AGENT_SOURCE_ADAPTER_IDS = ${tuple(adapterIds)};

/** Declared sources, then the catalog's coming-soon entries. */
export const AGENT_SOURCE_CATALOG_IDS = ${tuple(catalogIds)};
`;

const declarationsModule = `${header}
import type {
  AgentSourceAdapterId,
  AgentSourceCatalogEntry,
  AgentSourceDeclaration,
} from '@exawatt/core';

export const AGENT_SOURCE_DECLARATIONS = ${JSON.stringify(contract.sources, null, 2)} as const satisfies readonly AgentSourceDeclaration[];

export const FUTURE_AGENT_SOURCE_CATALOG = ${JSON.stringify(contract.comingSoon, null, 2)} as const satisfies readonly AgentSourceCatalogEntry[];

export function agentSourceDeclaration(
  adapterId: AgentSourceAdapterId
): AgentSourceDeclaration {
  const declaration = AGENT_SOURCE_DECLARATIONS.find(
    candidate => candidate.adapterId === adapterId
  );
  if (!declaration) throw new Error(\`Unknown Agent Source: \${adapterId}\`);
  return declaration;
}
`;

const targets = [
  ['packages/core/src/generated/agent-source-ids.ts', idsModule],
  ['src/generated/agent-source-declarations.ts', declarationsModule],
  [
    'electron/main/pty/generated-agent-source-declarations.ts',
    declarationsModule,
  ],
];

const prettierConfig =
  (await resolveConfig(path.join(root, 'src', 'generated'))) ?? {};

const stale = [];
for (const [relativePath, rawSource] of targets) {
  const absolute = path.join(root, relativePath);
  const source = await format(rawSource, {
    ...prettierConfig,
    parser: 'typescript',
  });
  if (!CHECK) {
    await mkdir(path.dirname(absolute), { recursive: true });
    await writeFile(absolute, source);
    continue;
  }
  const current = await readFile(absolute, 'utf8').catch(() => null);
  if (current !== source) stale.push(relativePath);
}

if (stale.length > 0) {
  throw new Error(
    `${stale.join(', ')} ${stale.length === 1 ? 'is' : 'are'} stale; run pnpm agent-sources:generate and commit the result`
  );
}
if (CHECK) {
  process.stdout.write(
    `[agent-sources] ${targets.length} generated files match contracts/agent-sources.json\n`
  );
}
